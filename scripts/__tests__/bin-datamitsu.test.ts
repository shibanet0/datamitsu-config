import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { detectBinaryCommand } from "../../bin/detect-binary-command.js";

const ROOT = join(import.meta.dirname, "../..");
const BIN = join(ROOT, "bin/datamitsu.js");
const BASE_CONFIG = join(ROOT, "datamitsu.config.base.js");

describe("bin/datamitsu.js", () => {
  // The wrapper must always inject --before-config so every datamitsu
  // invocation resolves the same base config (and configHash). Dropping this
  // flag is the root cause of the "wrong configHash → offline exec fails" class
  // of bugs.
  it("injects the --before-config flag", () => {
    expect(readFileSync(BIN, "utf8")).toContain("--before-config");
  });

  it("points --before-config at an existing datamitsu.config.base.js", () => {
    // Generated by `pnpm build`; present after setup-environment runs prepare.
    expect(existsSync(BASE_CONFIG)).toBe(true);
  });

  // The shim decides what facts().binaryCommand bakes into managed hook files,
  // so each package manager must get a command its own runtime can execute.
  it.each([
    ["pnpm/12.14.0 npm/? node/v22.12.0 linux x64", "pnpm datamitsu"],
    ["npm/10.9.0 node/v22.12.0 linux x64 workspaces/false", "npm exec --no -- datamitsu"],
    ["yarn/4.9.1 npm/? node/v22.12.0 linux x64", "yarn datamitsu"],
    ["bun/1.2.0 npm/? node/v22.12.0 linux x64", "bun run datamitsu"],
    [undefined, "pnpm datamitsu"],
    ["pip/25.0 cpython/3.13", "pnpm datamitsu"],
  ])("detects the package manager from %s", (userAgent, want) => {
    expect(detectBinaryCommand(userAgent)).toBe(want);
  });
});
